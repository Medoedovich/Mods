[CmdletBinding()]
param([Parameter(Mandatory=$true)][string]$WorldsRoot)
$ErrorActionPreference = 'Stop'
$taskProject = Split-Path -Parent $PSScriptRoot
$taskMaps = @(
    @{Name='Chernarus';World='chernarusplus';Bit=1},
    @{Name='Livonia';World='enoch';Bit=2},
    @{Name='Sakhal';World='sakhal';Bit=4},
    @{Name='Nasdara';World='nasdara';Bit=8}
)
$taskMasks = @{}
$taskSources = @()
foreach ($taskMap in $taskMaps) {
    $taskPath = Join-Path $WorldsRoot ($taskMap.World+'\ce\mapgrouppos.xml')
    [xml]$taskXml = [IO.File]::ReadAllText($taskPath)
    $taskNames = @($taskXml.map.group | ForEach-Object { ([string]$_.name).ToLowerInvariant() } | Sort-Object -Unique)
    if ($taskNames.Count -lt 100) { throw ('Unexpectedly small map catalog: '+$taskMap.Name) }
    foreach ($taskName in $taskNames) {
        if ($taskName -notmatch '^[a-z0-9_]+$') { throw ('Unsafe classname: '+$taskName) }
        $taskMasks[$taskName] = ([int]$taskMasks[$taskName]) -bor $taskMap.Bit
    }
    $taskSources += [ordered]@{Map=$taskMap.Name;World=$taskMap.World;Classes=$taskNames.Count;SHA256=(Get-FileHash -LiteralPath $taskPath).Hash}
}
$taskLines = @(
    '// Generated by tools/Update-MapCatalog.ps1 from official terrain CE mapgrouppos.xml files.',
    '// Membership means a static CE loot group occurs on that map, not asset origin.',
    '// Bohemia Interactive source data: ADPL-SA. See docs/MAP-CATALOG.md.',
    'class IOTMapCatalog',
    '{',
    '    static void Populate(map<string,int> masks)',
    '    {'
)
foreach ($taskName in @($taskMasks.Keys | Sort-Object)) {
    $taskLines += ('        masks.Insert("'+$taskName+'",'+$taskMasks[$taskName]+');')
}
$taskLines += @(
    '    }',
    '',
    '    static bool Matches(map<string,int> masks, string classname, int selection)',
    '    {',
    '        if (selection == 0) return true;',
    '        if (selection < 1 || selection > 4) return false;',
    '        classname.ToLower();',
    '        int bit = 1 << (selection - 1);',
    '        return (masks.Get(classname) & bit) != 0;',
    '    }',
    '}'
)
$taskOutput = Join-Path $taskProject 'src\iot\proxytool\scripts\5_Mission\IOTMapCatalog.c'
[IO.File]::WriteAllText($taskOutput,($taskLines -join "`r`n")+"`r`n",[Text.UTF8Encoding]::new($false))
$taskManifest = [ordered]@{Source='Bohemia Interactive DayZ terrain CE files';Definition='Static CE group classnames present in mapgrouppos.xml, intersected with loaded building/wreck classes at runtime';License='ADPL-SA';Maps=$taskSources;UniqueClasses=$taskMasks.Count;GeneratedSHA256=(Get-FileHash -LiteralPath $taskOutput).Hash}
$taskManifest | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath (Join-Path $taskProject 'docs\map-catalog-sources.json') -Encoding UTF8
$taskManifest | ConvertTo-Json -Depth 5
